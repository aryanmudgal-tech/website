// Builds proto/page-crumple/whole-page-crumple.html from the template and the packed crumple strips.
// The page is artifact-ready (no doctype or html/head/body tags).
import { readFileSync, writeFileSync } from 'node:fs';

const T = JSON.parse(readFileSync('out/page-d.json', 'utf8'));
const M = JSON.parse(readFileSync('out/page-m.json', 'utf8'));
const CR = 0.72;               // share of the runway spent crumpling; the rest is the roll
const ROLL0 = 0.74;
const pct = v => +(v * 100).toFixed(3);

function stops(meta) {
  const out = [];
  meta.ts.forEach((t, i) => out.push({ k: i, p: 0.02 + (CR - 0.02) * t }));
  for (let j = 0; j < meta.roll; j++) out.push({ k: meta.crumple + j, p: ROLL0 + (1 - ROLL0) * (j + 1) / meta.roll });
  return out;
}

function frames(name, meta, file) {
  const n = meta.crumple + meta.roll, S = stops(meta);
  const pos = k => +(k / (n - 1) * 100).toFixed(4);
  let mask = `@keyframes mask-${name} {\n  0% { -webkit-mask-image: none; mask-image: none; }\n`;
  let fx = `@keyframes fx-${name} {\n  0% { opacity: 0; background-position: 0% 100%; }\n`;
  let content = `@keyframes content-${name} {\n  0% { transform: none; }\n`;
  for (const s of S) {
    mask += `  ${pct(s.p)}% { -webkit-mask-image: url(${file}); mask-image: url(${file}); -webkit-mask-position: ${pos(s.k)}% 100%; mask-position: ${pos(s.k)}% 100%; }\n`;
    fx += `  ${pct(s.p)}% { opacity: .82; background-position: ${pos(s.k)}% 100%; }\n`;
    const b = meta.boxes[Math.min(s.k, meta.crumple - 1)];
    const sx = b.x1 - b.x0, sy = b.y1 - b.y0, cx = (b.x0 + b.x1) / 2 - 0.5, cy = (b.y0 + b.y1) / 2 - 0.5;
    content += `  ${pct(s.p)}% { transform: translate(${(cx * 100).toFixed(2)}vw, ${(cy * 100).toFixed(2)}svh) scale(${sx.toFixed(4)}, ${sy.toFixed(4)}); }\n`;
  }
  mask += `  100% { -webkit-mask-image: url(${file}); mask-image: url(${file}); -webkit-mask-position: 100% 100%; mask-position: 100% 100%; }\n}\n`;
  fx += `  100% { opacity: .82; background-position: 100% 100%; }\n}\n`;
  content += '}\n';
  return { css: mask + fx + content, n };
}

const d = frames('d', T, 'crumple-d.avif');
const m = frames('m', M, 'crumple-m.avif');
const css = `/* generated by build-whole-page.mjs: ${d.n} desktop frames, ${m.n} phone frames; crumple ends at ${CR * 100}% of each runway, the roll fills the rest */\n` + d.css + m.css;
const tpl = readFileSync('whole-page.template.html', 'utf8');
writeFileSync('../../page-crumple/whole-page-crumple.html', tpl.replace('/*KEYFRAMES*/', css).replaceAll('__N_D__', String(d.n * 100)).replaceAll('__N_M__', String(m.n * 100)));
console.log('wrote whole-page-crumple.html');
