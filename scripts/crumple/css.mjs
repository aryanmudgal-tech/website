// Turns src/data/crumple.json into src/styles/crumple.css: the mask, crease and content keyframes of spec 8.4,
// one set per screen shape. `node scripts/crumple/css.mjs --check` fails if the committed file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const CRUMPLE_END = 0.72; // share of the runway spent crumpling
export const ROLL_START = 0.74; // the roll fills the rest
const pct = (v) => +(v * 100).toFixed(3);

function stops(set) {
  const out = set.ts.map((t, k) => ({ k, p: 0.02 + (CRUMPLE_END - 0.02) * t }));
  for (let j = 0; j < set.roll; j++) out.push({ k: set.crumple + j, p: ROLL_START + (1 - ROLL_START) * (j + 1) / set.roll });
  return out;
}

function keyframes(name, set, file) {
  const n = set.crumple + set.roll;
  const at = (k) => +(k / (n - 1) * 100).toFixed(4);
  let mask = `@keyframes mask-${name} {\n  0% { mask-image: none; }\n`;
  let fx = `@keyframes fx-${name} {\n  0% { opacity: 0; background-position: 0% 100%; }\n`;
  let content = `@keyframes content-${name} {\n  0% { transform: none; }\n`;
  for (const { k, p } of stops(set)) {
    mask += `  ${pct(p)}% { mask-image: url(${file}); mask-position: ${at(k)}% 100%; }\n`;
    fx += `  ${pct(p)}% { opacity: 0.82; background-position: ${at(k)}% 100%; }\n`;
    const [x0, y0, x1, y1] = set.boxes[Math.min(k, set.crumple - 1)];
    const cx = (x0 + x1) / 2 - 0.5, cy = (y0 + y1) / 2 - 0.5;
    content += `  ${pct(p)}% { transform: translate(${(cx * 100).toFixed(2)}vw, ${(cy * 100).toFixed(2)}svh) scale(${(x1 - x0).toFixed(4)}, ${(y1 - y0).toFixed(4)}); }\n`;
  }
  mask += `  100% { mask-image: url(${file}); mask-position: 100% 100%; }\n}\n`;
  fx += '  100% { opacity: 0.82; background-position: 100% 100%; }\n}\n';
  content += '}\n';
  return mask + fx + content;
}

export function crumpleCss(data) {
  const n = (s) => data[s].crumple + data[s].roll;
  return `/* Generated by scripts/crumple/css.mjs from src/data/crumple.json; do not edit. ${n('d')} landscape and ${n('m')} portrait frames;
   each crumple ends at ${CRUMPLE_END * 100}% of its runway and the roll fills the rest (spec 8.4). */\n`
    + keyframes('d', data.d, '../assets/paper/crumple-d.avif') + keyframes('m', data.m, '../assets/paper/crumple-m.avif');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const data = JSON.parse(readFileSync(path.join(root, 'src', 'data', 'crumple.json'), 'utf8'));
  const file = path.join(root, 'src', 'styles', 'crumple.css');
  const css = crumpleCss(data);
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== css) { console.error('src/styles/crumple.css is stale; run npm run crumple'); process.exit(1); }
  } else {
    writeFileSync(file, css);
    console.log('wrote src/styles/crumple.css');
  }
}
